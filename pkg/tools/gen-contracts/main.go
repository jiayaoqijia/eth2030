// gen-contracts regenerates eiptest/contracts/gen.go from the
// eiptest/contracts/*.bin-runtime files produced by solc (make contracts).
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	dir := "eiptest/contracts"
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "read %s: %v\n", dir, err)
		os.Exit(1)
	}
	var names []string
	for _, e := range entries {
		if strings.HasSuffix(e.Name(), ".bin-runtime") {
			names = append(names, strings.TrimSuffix(e.Name(), ".bin-runtime"))
		}
	}
	sort.Strings(names)
	if len(names) == 0 {
		fmt.Fprintf(os.Stderr, "no .bin-runtime files in %s (run solc first)\n", dir)
		os.Exit(1)
	}

	var b strings.Builder
	b.WriteString("// Code generated by tools/gen-contracts (make contracts) from eiptest/contracts/*.sol. DO NOT EDIT.\n\npackage contracts\n")
	for _, n := range names {
		hex, err := os.ReadFile(filepath.Join(dir, n+".bin-runtime"))
		if err != nil {
			fmt.Fprintf(os.Stderr, "read %s: %v\n", n, err)
			os.Exit(1)
		}
		fmt.Fprintf(&b, "\n// %s runtime bytecode (solc, bin-runtime).\nconst %sRuntime = %q\n", n, n, strings.TrimSpace(string(hex)))
	}

	out := filepath.Join(dir, "gen.go")
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write %s: %v\n", out, err)
		os.Exit(1)
	}
	fmt.Printf("regenerated %s (%d contracts)\n", out, len(names))
}
