// gen-contracts regenerates eiptest/contracts/gen.go from the
// eiptest/contracts/*.bin-runtime files produced by solc (make contracts).
package main

import (
	"encoding/hex"
	"fmt"
	"go/format"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	dir := "eiptest/contracts"
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "read %s: %v\n", dir, err)
		os.Exit(1)
	}
	var names []string
	for _, e := range entries {
		if strings.HasSuffix(e.Name(), ".bin-runtime") {
			names = append(names, strings.TrimSuffix(e.Name(), ".bin-runtime"))
		}
	}
	sort.Strings(names)
	if len(names) == 0 {
		fmt.Fprintf(os.Stderr, "no .bin-runtime files in %s (run solc first)\n", dir)
		os.Exit(1)
	}

	var b strings.Builder
	b.WriteString("// Code generated by tools/gen-contracts (make contracts). DO NOT EDIT.\n\npackage contracts\n\nimport _ \"embed\"\n")
	for _, n := range names {
		if !token.IsIdentifier(n) {
			fmt.Fprintf(os.Stderr, "invalid Go identifier %q\n", n)
			os.Exit(1)
		}
		data, err := os.ReadFile(filepath.Join(dir, n+".bin-runtime"))
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		decoded, err := hex.DecodeString(strings.TrimSpace(string(data)))
		if err != nil || len(decoded) == 0 {
			fmt.Fprintf(os.Stderr, "invalid or empty bytecode for %s: %v\n", n, err)
			os.Exit(1)
		}
		fmt.Fprintf(&b, "\n//go:embed %s.bin-runtime\nvar %sRuntime string\n", n, n)
	}
	b.WriteString("\nvar named = map[string]*string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "%q: &%sRuntime,\n", n, n)
	}
	b.WriteString("}\n")
	b.WriteString("\n// Names lists the available scenario contracts.\nfunc Names() []string { return []string{")
	for _, n := range names {
		fmt.Fprintf(&b, "%q, ", n)
	}
	b.WriteString("} }\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\n// %s returns the %s runtime bytecode.\nfunc (Named) %s() []byte { return mustRuntime(%q) }\n", n, n, n, n)
	}
	out := filepath.Join(dir, "gen.go")
	formatted, err := format.Source([]byte(b.String()))
	if err == nil {
		err = os.WriteFile(out, formatted, 0o644)
	}
	if err != nil {
		fmt.Fprintf(os.Stderr, "generate %s: %v\n", out, err)
		os.Exit(1)
	}
	fmt.Printf("regenerated %s (%d contracts)\n", out, len(names))
}
