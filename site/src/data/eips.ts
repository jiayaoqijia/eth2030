// ETH2030 EIP / roadmap progress — single source of truth.
//
// Fork placement follows the L1 Strawmap revision of Nov 2, 2026 (strawmap.org).
// Implementation status / file paths come from eth2030 docs:
//   - docs/EIP_SPEC_IMPL.md      (traceability matrix, per-EIP files & tests)
//   - CLAUDE.md L70-71           (complete / substantial lists)
//   - docs/GAP_ANALYSIS.md       (65 roadmap-item audit)
//   - workspace docs/EIP_IMPLEMENTATION_GAP_ANALYSIS.md (completeness % + P0/P1/P2 for 11 key EIPs)
//
// Update flow: run `npx tsx scripts/verify-eips.ts` after code changes, fix
// discrepancies here, then commit. See docs/EIP_TRACKER.md in the repo root.

export type Layer = 'CL' | 'DL' | 'EL' | 'cross';

export type ForkId =
  | 'pre'
  | 'glamsterdam'
  | 'hegota'
  | 'i'
  | 'j'
  | 'k'
  | 'l'
  | 'longer'
  | 'infra';

export type Status =
  | 'complete'
  | 'substantial'
  | 'functional'
  | 'referenced'
  | 'partial'
  | 'planned';

export type Priority = 'P0' | 'P1' | 'P2';

export interface StrawmapPlacement {
  /** Box label on the Nov 2, 2026 strawmap. */
  item: string;
  /** Strawmap marker: SFI = selected for inclusion, CFI = considered for inclusion, EIP = tracked as an EIP. */
  tag?: 'SFI' | 'CFI' | 'EIP';
  /** Headliner (one CL + one EL per fork on the strawmap). */
  headliner?: boolean;
  /** Grey box = offchain upgrade. */
  offchain?: boolean;
  /** Cross-layer (purple) box. */
  crossLayer?: boolean;
}

export interface EipEntry {
  /** Page id, e.g. `eip-7928` or `feature-quick-slots`. */
  id: string;
  /** EIP number; null for framework / roadmap features. */
  number: number | null;
  title: string;
  layer: Layer;
  fork: ForkId;
  /** Doc grouping this entry was sourced from. */
  category: string;
  status: Status;
  /** Implementation completeness 0-100 (gap analysis where available). */
  completeness?: number;
  priority?: Priority;
  specUrl?: string;
  specStatus?: string;
  strawmap?: StrawmapPlacement;
  /** Implementation file paths relative to eth2030/pkg/. */
  implementation: string[];
  /** Test file paths relative to eth2030/pkg/. */
  tests: string[];
  /** Known gaps vs. the EIP spec (from gap analysis). */
  gaps?: string[];
  /** What is already implemented (deep-analysis EIPs only). */
  implemented?: string[];
  summary?: string;
}

export interface ForkInfo {
  id: ForkId;
  name: string;
  /** Strawmap column label / target window. */
  year: string;
  headliners: { layer: Layer; item: string }[];
}

