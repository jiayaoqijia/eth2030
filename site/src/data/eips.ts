export const forkOrder: Record<ForkId, number> = Object.fromEntries(
  FORKS.map((f, i) => [f.id, i]),
) as Record<ForkId, number>;

export const forkByName: Record<ForkId, ForkInfo> = Object.fromEntries(
  FORKS.map((f) => [f.id, f]),
) as Record<ForkId, ForkInfo>;

export function entriesByFork(): { fork: ForkInfo; entries: EipEntry[] }[] {
  return FORKS.map((fork) => ({
    fork,
    entries: EIPS.filter((e) => e.fork === fork.id),
  })).filter((g) => g.entries.length > 0);
}

export function getEntry(id: string): EipEntry | undefined {
  return EIPS.find((e) => e.id === id);
}

